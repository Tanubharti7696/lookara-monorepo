/**
 * Get current normalized language key
 */
export function getCurrentLanguage() {
  const pref = (localStorage.getItem('lookara_pref_language') || 'English (US)').toLowerCase();
  if (pref.includes('es') || pref.includes('span')) return 'es';
  if (pref.includes('fr') || pref.includes('fren')) return 'fr';
  if (pref.includes('uk')) return 'en-UK';
  return 'en-US';
}

/**
 * Translate a phrase
 */
export function t(key) {
  const lang = getCurrentLanguage();
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en-US']?.[key] || key;
}

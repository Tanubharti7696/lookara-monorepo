export default function DevTrustSidebar({ open, onClose }: { open: boolean; onClose: () => void }) {
  const handleExit = () => {
    localStorage.removeItem('lookara_token');
    localStorage.removeItem('lookara_user');
    localStorage.removeItem('lookara_workspace');
    sessionStorage.clear();
    const metaEnv = (import.meta as any).env;
    const target = metaEnv?.VITE_PUBLIC_PORTAL_URL
      ? `${metaEnv.VITE_PUBLIC_PORTAL_URL}/login`
      : (window.location.hostname === 'localhost' ? 'http://localhost:5173/login' : 'https://public-portal-cyan.vercel.app/login');
    window.location.href = target;
  };

  return (
    <>
      <div
        className={`dt-sidebar-overlay${open ? ' is-open' : ''}`}
        onClick={onClose}
        aria-hidden="true"
      />
      <nav className={`dt-sidebar${open ? ' is-open' : ''}`} aria-label="Developer portal navigation">
        <div className="dt-sidebar__nav-content">
          {NAV.map((group) => (
            <div key={group.label}>
              <div className="dt-sidebar__label">{group.label}</div>
              {group.items.map((item) => (
                <NavLink
                  key={item.to}
                  to={item.to}
                  className={({ isActive }) => `dt-nav-item${isActive ? ' is-active' : ''}`}
                >
                  <svg viewBox="0 0 20 20" fill="currentColor">
                    <path fillRule="evenodd" d={item.icon} clipRule="evenodd" />
                  </svg>
                  {item.label}
                </NavLink>
              ))}
            </div>
          ))}
        </div>
        <div className="dt-sidebar__footer">
          <button
            type="button"
            className="dt-exit-btn"
            onClick={handleExit}
            title="Exit Portal / Sign Out"
            aria-label="Exit Portal"
          >
            <svg viewBox="0 0 24 24" width="15" height="15" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
              <path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4" />
              <polyline points="16 17 21 12 16 7" />
              <line x1="21" y1="12" x2="9" y2="12" />
            </svg>
            <span>Exit Portal</span>
          </button>
        </div>
      </nav>
    </>
  );
}